import type { ExamOption, ExamQuestion, ExamTopic } from "@/lib/exam/types";

function q(
  id: string,
  topic: ExamTopic,
  moduleId: string,
  prompt: string,
  labels: [string, string, string, string],
  correctIndex: number,
  explanation: string,
): ExamQuestion {
  const options: ExamOption[] = labels.map((label, index) => ({
    id: String.fromCharCode(97 + index),
    label,
  }));

  return {
    id,
    topic,
    moduleId,
    prompt,
    options,
    correctOptionId: String.fromCharCode(97 + correctIndex),
    explanation,
  };
}

